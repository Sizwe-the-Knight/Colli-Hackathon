export function BriefNarrationControl({ narration, generating, notice, updated, onGenerate }: {
  narration: BriefNarration | null; generating: boolean; notice: string; updated: boolean; onGenerate: () => void;
}) {
  const fresh = updated && narration?.source === 'nemotron' && narration.status === 'generated';
  const status = generating ? 'Preparing a Nemotron explanation of this synthetic example…' : notice ||
    (fresh ? 'Brief updated with NVIDIA Nemotron via Nebius. Based on synthetic demonstration evidence.' :
      narration?.source === 'nemotron' ? narration.status === 'cached'
        ? 'Previously generated by NVIDIA Nemotron via Nebius. Reused for this synthetic example.'
        : 'Explanation generated by NVIDIA Nemotron via Nebius. Based on synthetic demonstration evidence.' :
      narration?.status === 'disabled' ? 'Deterministic, evidence-based explanation. Nemotron generation is currently off.' :
      narration?.status && narration.status !== 'available' ? 'Deterministic, evidence-based explanation. Nemotron is unavailable or this example was already attempted; no automatic retry.' :
      'Deterministic, evidence-based explanation. Nemotron generation is optional.');
  return <div className="brief-narrator">
    {narration?.status === 'available' && <>
      <button className="brief-primary" type="button" disabled={generating} aria-busy={generating} aria-describedby="brief-narration-note" onClick={onGenerate}>{generating ? 'Preparing explanation…' : 'Explain with NVIDIA Nemotron'}</button>
      <p id="brief-narration-note">Optional: sends only this synthetic example to Nebius. Limited demo allowance; no personal account activity is sent.</p>
    </>}
    <p role="status" aria-atomic="true" className={fresh ? 'brief-narration-success' : undefined}>{status}</p>
  </div>;
}

export function BriefContent({ report, narration, narrationControl, highlightExplanation = false }: { report: OperationalBrief; narration?: BriefNarration | null; narrationControl?: React.ReactNode; highlightExplanation?: boolean }) {
  const lead = centralFinding(report);
  const story = narration?.source === 'nemotron' && narration.findingId === lead?.id ? narration.narrative : null;
  const current = report.periods.current;
  const empty = current.totals.activities === 0;
  const explanation = lead ? findingExplanation(lead, report) : null;
  return <article className="brief-card" aria-labelledby="brief-title">
    <header className="brief-edition">
      <h1 id="brief-title">Daily Executive Brief</h1>
      <p className="brief-period">{day(current.start)} – {day(current.end)} <span>(UTC · end date excluded)</span></p>
      <p className="brief-demo">{report.provenance.kind === 'synthetic' ? 'Demonstration · synthetic records' : 'User-supplied records · unverified'}</p>
    </header>
    <BriefHealthScore />
    <section className={`brief-feature${highlightExplanation && story && narration?.status === 'generated' ? ' brief-feature-updated' : ''}`} aria-labelledby="central-finding">
      <p className="brief-kicker">What happened?</p>
      <h2 id="central-finding">{story?.headline ?? (empty ? 'Not enough data to write your brief.' : lead ? findingHeadline(lead, report) : 'No supported finding is available.')}</h2>
      {(story || (!empty && explanation?.context)) && <p className="brief-narrative-context">{story?.whatHappened ?? explanation?.context}</p>}
      <div className="brief-explanation">
        <div><h3>Why does it matter?</h3><p>{story?.whyItMatters ?? (empty ? "We don't have activity records for this period. We can't tell what was spent or whether anything went wrong." : explanation?.significance ?? "We don't yet have enough information to assess how things are working.")}</p></div>
        <div><h3>What should I do next?</h3><p>{story?.nextStep ?? (empty ? 'Add activity records for two consecutive periods and check that they cover both periods.' : explanation?.nextStep ?? 'Check which records are missing before drawing conclusions.')}</p></div>
      </div>
      {narrationControl}
    </section>
    <p className="brief-provenance">{report.provenance.kind === 'synthetic' ? 'An example, not your private account activity.' : 'Based on supplied records, not independently verified.'}</p>
    <div className="brief-actions">
      <Link className="brief-primary" href="/dashboard">Continue to Dashboard <ArrowUpRight size={17} aria-hidden="true" /></Link>
      <p className="brief-destination">Explore the Control Panel. Its operational metrics are still sample data.</p>
    </div>
  </article>;
}

export function Brief() {
  const query = useQuery({ queryKey: ['operational-brief'], queryFn: async ({ signal }) =>
    operationalBriefSchema.parse(await getOperationalBrief(signal)), retry: false });
  const [narration, setNarration] = useState<{ report: unknown; value: BriefNarration } | null>(null);
  const [notice, setNotice] = useState('');
  const [generating, setGenerating] = useState(false);
  const [updated, setUpdated] = useState(false);
  const generation = useRef<AbortController | null>(null);
  useEffect(() => {
    const controller = new AbortController();
    setNarration(null); setNotice(''); setGenerating(false); setUpdated(false);
    if (query.data && !query.error) {
      // Cache read only: no inference, polling, retries or provider calls here.
      void getBriefNarration(controller.signal).then(narrationSchema.parse).then(value => {
        if (!controller.signal.aborted) setNarration({ report: query.data, value });
      }).catch(() => { if (!controller.signal.aborted) setNotice('Showing the deterministic, evidence-based explanation.'); });
    }
    return () => { controller.abort(); generation.current?.abort(); generation.current = null; };
  }, [query.data, query.error]);
  const currentNarration = narration && narration.report === query.data ? narration.value : null;
  const generate = async () => {
    if (generation.current || currentNarration?.status !== 'available') return;
    const controller = new AbortController(); generation.current = controller; setGenerating(true); setNotice(''); setUpdated(false);
    try {
      const value = narrationSchema.parse(await generateBriefNarration(currentNarration.fingerprint, controller.signal));
      if (value.fingerprint !== currentNarration.fingerprint) throw new Error('Report changed');
      if (!controller.signal.aborted) {
        setNarration({ report: query.data, value });
        setUpdated(value.source === 'nemotron' && value.status === 'generated');
        if (value.source !== 'nemotron') setNotice('Nemotron wording is unavailable or its allowance has been reached. Showing the deterministic, evidence-based explanation. No automatic retry will be made.');
      }
    } catch { if (!controller.signal.aborted) {
      setNotice('AI wording could not be confirmed. Showing the deterministic explanation. No automatic retry will be made.');
      setNarration({ report: query.data, value: { ...currentNarration, status: 'unavailable' } });
    } } finally { if (!controller.signal.aborted) setGenerating(false); if (generation.current === controller) generation.current = null; }
  };
  // Never let a failed refresh present stale findings as current information.
  const parsed = !query.error && operationalBriefSchema.safeParse(query.data);
  if (!query.isLoading && (!parsed || !parsed.success)) return <ApiUnavailable subject="Daily Brief" onRetry={() => { void query.refetch(); }} />;
  return <div className="executive-brief">
    <header className="brief-masthead"><Link href="/brief" aria-label="Colli Daily Brief"><img src="/colli-icon.png" alt="" /><span>Colli</span></Link>
      </header>
    <main className="brief-main">{parsed && parsed.success ? <BriefReveal><BriefContent report={parsed.data} narration={currentNarration} highlightExplanation={updated} narrationControl={
      <BriefNarrationControl narration={currentNarration} generating={generating} notice={notice} updated={updated} onGenerate={() => { void generate(); }} />
    } /></BriefReveal> :
      <section className="brief-loading" role="status"><p className="brief-kicker">Daily Executive Brief</p><h1>Preparing your edition…</h1><p>Checking the available records and their coverage.</p><Link href="/dashboard">Continue to Dashboard</Link></section>}</main>
    <LegalFooter />
  </div>;
}
